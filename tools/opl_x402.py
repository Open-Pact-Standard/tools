def validate_config(price: str, asset: str, chain: str) -> list[str]:
    errors: list[str] = []
    try:
        amount = float(price)
        if amount <= 0:
            errors.append(f"Price must be positive, got {price}")
    except ValueError:
        errors.append(f"Invalid price: {price}")
    if asset.upper() not in SUPPORTED_ASSETS:
        errors.append(f"Unsupported asset: {asset}. Use one of: {', '.join(SUPPORTED_ASSETS)}")
    if chain.lower() not in SUPPORTED_CHAINS:
        errors.append(f"Unsupported chain: {chain}. Use one of: {', '.join(SUPPORTED_CHAINS)}")
    return errors



