"""x402 Payment Generator for OPL

Generates HTTP 402 payment integration code and configuration
for accepting crypto payments via the x402 protocol.

Usage:
    python3 opl_x402.py generate --framework fastapi --price 0.01 --asset USDC --chain base
    python3 opl_x402.py config --price 5.00 --asset USDC --chain base --recipient 0x...
    python3 opl_x402.py chains
    python3 opl_x402.py assets
"""
