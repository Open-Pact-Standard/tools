def main() -> None:
    parser = argparse.ArgumentParser(
        description="x402 Payment Generator for OPL -- generates HTTP 402 crypto payment integration code")
    parser.add_argument("--version", action="version", version=f"OPL Adoption Tools {__version__}")
    sub = parser.add_subparsers(dest="command", help="Available commands")

    gen = sub.add_parser("generate", help="Generate a payment endpoint for a Python framework")
    gen.add_argument("--framework", choices=["fastapi", "flask"], default="fastapi",
                     help="Python framework (default: fastapi)")
    gen.add_argument("--price", required=True, help="Price per access (e.g. 0.01, 1.00)")
    gen.add_argument("--asset", default="USDC", help="Stablecoin (default: USDC)")
    gen.add_argument("--chain", default="base", help="Blockchain network (default: base)")
    gen.add_argument("--description", default="Premium content access",
                     help="Payment description")
    gen.add_argument("--output", help="Output file path (default: stdout)")

    cfg = sub.add_parser("config", help="Generate an x402 payment configuration JSON")
    cfg.add_argument("--price", required=True, help="Price per access (e.g. 0.01, 1.00)")
    cfg.add_argument("--asset", default="USDC", help="Stablecoin (default: USDC)")
    cfg.add_argument("--chain", default="base", help="Blockchain network (default: base)")
    cfg.add_argument("--recipient", default=DEFAULT_RECIPIENT,
                     help="Payment recipient address")
    cfg.add_argument("--description", default="OPL commercial use",
                     help="Payment description")
    cfg.add_argument("--output", help="Output file path (default: stdout)")

    sub.add_parser("chains", help="List supported chains")
    sub.add_parser("assets", help="List supported assets")

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        sys.exit(1)

    if args.command == "generate":
        errors = validate_config(args.price, args.asset, args.chain)
        if errors:
            for e in errors:
                print(f"Error: {e}", file=sys.stderr)
            sys.exit(1)
        price = float(args.price)
        gen_fn = _fastapi_code if args.framework == "fastapi" else _flask_code
        code = gen_fn(price, args.asset.upper(), args.chain.lower(), args.description)
        if args.output:
            Path(args.output).write_text(code)
            print(f"Generated {args.framework} endpoint -> {args.output}")
        else:
            print(code)

    elif args.command == "config":
        errors = validate_config(args.price, args.asset, args.chain)
        if errors:
            for e in errors:
                print(f"Error: {e}", file=sys.stderr)
            sys.exit(1)
        if args.recipient == DEFAULT_RECIPIENT:
            print("WARNING: Using default zero-address as recipient. "
                  "Payments sent to the zero address will be unrecoverable. "
                  "Use --recipient to set your wallet address.", file=sys.stderr)
        config = generate_config(
            float(args.price), args.asset.upper(), args.chain.lower(),
            args.recipient, args.description)
        output = json.dumps(config, indent=2)
        if args.output:
            Path(args.output).write_text(output)
            print(f"Generated x402 config -> {args.output}")
        else:
            print(output)

    elif args.command == "chains":
        print("Supported chains:")
        for chain, name in SUPPORTED_CHAINS.items():
            print(f"  {chain:12s} {name}")

    elif args.command == "assets":
        print("Supported stablecoins:")
        for asset, name in SUPPORTED_ASSETS.items():
            print(f"  {asset:6s} {name}")


if __name__ == "__main__":
    main()
