def _build_endpoint_code(framework: str, price: float, asset: str,
                         chain: str, desc: str) -> str:
    """Build a payment endpoint file from a framework-specific config."""
    cfg = _FRAMEWORKS[framework]
    pay_to = "0x...YOUR_WALLET..."
    lines = [
        "#!/usr/bin/env python3",
        f'"""{cfg["docstring"]}"""',
        "",
        f"# Requirements: {cfg['requirements']}",
        "# For production: pip install x402  (Coinbase facilitator SDK)",
        "",
        *cfg["imports"],
        "",
        cfg["app_init"],
        "",
        "X402 = {",
        f'    "price": {price},',
        f'    "asset": "{asset}",',
        f'    "chain": "{chain}",',
        f'    "description": "{desc}",',
        f'    "payTo": "{pay_to}",',
        '    "facilitator_url": "https://x402.org/facilitator",',
        "}",
        "",
        "",
        cfg["route_decorator"],
        cfg["func_sig"],
        "    # Protected endpoint -- requires x402 payment.",
        f'    payment_signature = {cfg["header_access"]}',
        "",
        "    if not payment_signature:",
        *cfg["response_402"],
        "",
        "    # WARNING: Verification is NOT active in this template.",
        "    # Uncomment the code below and set up the x402 facilitator before deploying.",
        "    # Without verification, anyone can access this endpoint by providing any string.",
        "    #",
        "    # In production, verify with x402 facilitator:",
        *cfg["verify_prefix"],
        *cfg["verify_call"],
        "",
        cfg["success_return"],
        *cfg["main_block"],
    ]
    return "\n".join(lines) + "\n"


def _fastapi_code(price: float, asset: str, chain: str, desc: str) -> str:
    return _build_endpoint_code("fastapi", price, asset, chain, desc)


def _flask_code(price: float, asset: str, chain: str, desc: str) -> str:
    return _build_endpoint_code("flask", price, asset, chain, desc)

def generate_config(price: float, asset: str, chain: str,
                    recipient: str, description: str = "OPL commercial use") -> dict:
    return {
        "x402Version": 1,
        "config": {
            "price": price,
            "asset": asset,
            "network": chain,
            "payTo": recipient,
            "description": description,
            "facilitator": "https://x402.org/facilitator",
            "supportedChains": list(SUPPORTED_CHAINS.keys()),
            "supportedAssets": list(SUPPORTED_ASSETS.keys()),
        },
        "paymentChallenges": [
            {
                "network": chain,
                "maxAmountRequired": str(price),
                "resource": "/",
                "description": description,
                "mimeType": "application/json",
                "payTo": recipient,
                "extra": {},
            }
        ],
    }


